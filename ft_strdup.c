#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	len;
	char	*p;
	size_t	i;

	if (!s)
		return (NULL);
	len = ft_strlen(s);
	p = malloc(len + 1);
	if (!p)
		return (NULL);
	i = 0;
	while (s[i])
	{
		p[i] = s[i];
		i++;
	}
	p[i] = 0;
	return (p);
}
